"""Alembic env.py configured for SQLite via a synchronous engine.

Resolves the database URL from the application settings via
:func:`ekko.config.runtime.get_config`, and drives both offline (``--sql``) and
online migration modes with type and server-default comparison enabled.
"""

from __future__ import annotations

import logging
import logging.config
from typing import TYPE_CHECKING

from sqlalchemy import create_engine, pool

if TYPE_CHECKING:
    from collections.abc import Iterable

    from alembic.operations.ops import MigrationScript
    from alembic.runtime.migration import MigrationContext
    from sqlalchemy.engine import Connection

# isort: off
from alembic import context
from ekko.config.runtime import get_config
from ekko.infrastructure.db.models import User
# isort: on

config = context.config
if config.config_file_name is not None:
    logging.config.fileConfig(config.config_file_name)

_logger = logging.getLogger("alembic.env")

# Importing the ORM model registers its table before autogenerate compares metadata.
target_metadata = User.metadata


def _get_url() -> str:
    """Resolve the SQLAlchemy URL for migrations.

    Preference order:
    1. `sqlalchemy.url` in alembic.ini (useful for CI/managed runs)
    2. application settings (EKKO_ prefixed env vars)

    Returns:
        str: Resolved synchronous SQLAlchemy URL.
    """
    url = config.get_main_option("sqlalchemy.url")
    if url:
        return url
    return get_config().database_sync_url


def run_migrations_offline() -> None:
    """Run migrations in offline mode, emitting SQL without a DBAPI connection."""
    context.configure(
        url=_get_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        compare_type=True,
        compare_server_default=True,
    )
    _logger.info("Running migrations in offline mode")
    with context.begin_transaction():
        context.run_migrations()


def _prevent_empty_autogenerate(
    context: MigrationContext,
    revision: str | Iterable[str | None] | Iterable[str],
    directives: list[MigrationScript],
) -> None:
    """Discard autogenerated revisions that contain no schema changes.

    Args:
        context (MigrationContext): Active migration context.
        revision (str | Iterable[str | None] | Iterable[str]): Current revision(s).
        directives (list[MigrationScript]): Mutable list of generated directives.
    """
    if not getattr(config.cmd_opts, "autogenerate", False):
        return
    script = directives[0]
    if script.upgrade_ops is not None and script.upgrade_ops.is_empty():
        directives[:] = []
        _logger.info("No schema changes detected; skipping empty migration.")


def _do_run_migrations(connection: Connection) -> None:
    """Configure the context against a live connection and run migrations."""
    context.configure(
        connection=connection,
        target_metadata=target_metadata,
        compare_type=True,
        compare_server_default=True,
        process_revision_directives=_prevent_empty_autogenerate,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations in online mode against a live database connection."""
    connectable = create_engine(_get_url(), poolclass=pool.NullPool)
    try:
        with connectable.connect() as connection:
            _logger.info("Running migrations in online mode")
            _do_run_migrations(connection)
    finally:
        connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
